import { chromium } from '@playwright/test';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const origin=process.env.TEST_URL ?? 'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
const page=await context.newPage();
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
const assert=(value,message)=>{if(!value)throw new Error(message);};
const report=[];
try {
  await page.goto(origin);
  await page.waitForFunction(()=>document.querySelectorAll('.hidden-score').length===2,{},{timeout:60000});
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  assert((await page.locator('.team-card').count())===2,'Both teams missing');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
  const result=page.locator('.united .result');
  assert(!(await result.textContent()).match(/\d+\s*–\s*\d+/),'Initial spoiler');
  await page.getByRole('button',{name:'Näytä tulos',exact:true}).first().click();
  assert(await result.locator('.score').count()===1,'Reveal failed');
  assert(await page.locator('.steelers .hidden-score').count()===1,'Independent spoilers failed');
  await page.getByRole('button',{name:'Piilota tulos'}).click();
  assert(await result.locator('.hidden-score').count()===1,'Hide failed');
  await page.getByRole('button',{name:'Näytä tulos',exact:true}).first().click();
  await page.reload();
  await page.waitForSelector('.united .hidden-score');
  assert(await page.locator('.score').count()===0,'Reload spoiler');
  report.push('Real ESPN snapshot fallback (direct headless browser access blocked by Akamai 403), two teams, mobile 390px, reveal/hide, independent protection, reload: PASS');
  await mkdir('work',{recursive:true});
  await page.screenshot({path:'work/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop overflow');
  await page.screenshot({path:'work/desktop.png',fullPage:true});
  await page.evaluate(async()=>{const registration=await navigator.serviceWorker.ready; if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true})); return registration.scope;});
  const manifest=await page.evaluate(async()=>{const href=document.querySelector('link[rel=manifest]').href; const data=await(await fetch(href)).json(); for(const icon of data.icons){const r=await fetch(new URL(icon.src,href));if(!r.ok)throw new Error('Missing icon');} return data;});
  assert(manifest.display==='standalone','Manifest display');
  await context.setOffline(true);
  await page.reload();
  await page.waitForSelector('.united .hidden-score');
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  assert((await page.locator('#status').textContent()).toLowerCase().includes('offline'),'Offline warning');
  assert(await page.locator('.score').count()===0,'Cache spoiler');
  assert(await page.locator('.team-logo img').evaluateAll(images=>images.every(x=>x.complete&&x.naturalWidth>0)),'Offline logos');
  report.push('Desktop 1440px, service worker control, manifest icons, offline reload, offline logos and spoiler protection: PASS');
  // Deterministic browser responses for rollover and network failure.
  const fixture=JSON.parse(await readFile('tests/fixtures/soccer_all_teams_360_schedule_season_2026.json','utf8'));
  const event=structuredClone(fixture.events[0]);
  event.id='test-new-final'; event.date=new Date(Date.now()-60000).toISOString(); event.competitions[0].date=event.date;
  await page.getByRole('button',{name:'Näytä tulos',exact:true}).first().click();
  await page.route('**/site.api.espn.com/**',route=>route.fulfill({json:{events:[event]}}));
  await context.setOffline(false);
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  await page.getByRole('button',{name:'Päivitä tiedot'}).click();
  await page.waitForFunction(()=>document.querySelector('.united button[data-match]')?.dataset.match==='test-new-final');
  assert(await page.locator('.united .hidden-score').count()===1,'New game inherited reveal');
  await page.unroute('**/site.api.espn.com/**');
  await page.route('**/site.api.espn.com/**',route=>route.abort());
  await page.route('**/data/*.json*',route=>route.abort());
  await page.getByRole('button',{name:'Päivitä tiedot'}).click();
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('epäonnistui'));
  assert(await page.locator('.united button[data-match]').getAttribute('data-match')==='test-new-final','Network failure discarded cache');
  report.push('New finished game auto-hides, transient API failure preserves previous data: PASS');
  assert(errors.length===0,`Browser errors: ${errors}`);
  await writeFile('work/browser-verification.json',JSON.stringify({checkedAt:new Date().toISOString(),report},null,2));
  console.log(report.join('\n'));
} catch(error) { console.log('Status:',await page.locator('#status').textContent().catch(()=>'')); await mkdir('work',{recursive:true}); await page.screenshot({path:'work/browser-failure.png',fullPage:true}); throw error; } finally {await browser.close();}
