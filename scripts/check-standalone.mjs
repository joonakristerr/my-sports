import { chromium } from '@playwright/test';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch();
try {
  const context=await browser.newContext({viewport:{width:390,height:844},offline:true});
  const page=await context.newPage(),errors=[],localRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().startsWith('file:'))localRequests.push(r.url());});
  await page.goto(pathToFileURL(resolve('My Sports.html')).href);
  await page.waitForSelector('.united .hidden-score');
  const styles=await page.evaluate(()=>({background:getComputedStyle(document.documentElement).backgroundColor,card:getComputedStyle(document.querySelector('.team-card')).backgroundColor,matches:getComputedStyle(document.querySelector('.matches')).display,button:getComputedStyle(document.querySelector('.reveal')).minHeight}));
  if(styles.background!=='rgb(16, 19, 21)' || styles.card!=='rgb(25, 30, 32)' || styles.matches!=='grid' || styles.button!=='44px')throw new Error(`Standalone CSS missing: ${JSON.stringify(styles)}`);
  await mkdir('work',{recursive:true});
  await page.screenshot({path:'work/standalone-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  if(!await page.locator('.matches').first().evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length===2))throw new Error('Desktop columns missing');
  await page.screenshot({path:'work/standalone-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.locator('.team-card').count()!==2)throw new Error('Missing teams');
  if(!await page.locator('.team-logo img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0)))throw new Error('Missing embedded logos');
  await page.getByRole('button',{name:'Näytä tulos',exact:true}).first().click();
  if(await page.locator('.united .score').count()!==1 || await page.locator('.steelers .hidden-score').count()!==1)throw new Error('Reveal/independence failed');
  await page.getByRole('button',{name:'Piilota tulos'}).click();
  await page.getByRole('button',{name:'Näytä tulos',exact:true}).first().click();
  await page.reload();
  if(await page.locator('.score').count())throw new Error('Reload spoiler');
  await page.locator('button[data-video-team]').first().click();
  if(await page.locator('.video-dialog').count()!==1 || await page.locator('.video-dialog video,.video-dialog img,.video-dialog iframe').count())throw new Error('Unsafe video preview');
  await page.getByRole('button',{name:'Sulje',exact:true}).click();
  if(await page.locator('.score').count())throw new Error('Video revealed score');
  if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))throw new Error('Mobile overflow');
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  await page.getByRole('button',{name:'Päivitä tiedot'}).click();
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  if(await page.locator('.hidden-score').count()!==2)throw new Error('Offline refresh lost data');
  if(localRequests.length!==2)throw new Error(`Additional local files requested: ${localRequests}`);
  if(errors.length)throw new Error(errors.join('\n'));
  await context.setOffline(false);
  await page.reload();
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled,{},{timeout:30000});
  console.log('PASS: file:// opens offline; embedded logos; no other local files; mobile layout; reveal/hide; independent protection; reload; video targets; offline refresh retains data.');
  console.log('Online file:// status:',await page.locator('#status').textContent());
} finally {await browser.close();}
